# ---------------------------------------------------------------------

MENU = [
    ("Прямой участок воздуховода круглого сечения", straight_round),
    ("Прямой участок воздуховода прямоугольного сечения", straight_rect),
    ("Отвод круглого сечения", elbow_round),
    ("Отвод прямоугольного сечения", elbow_rect),
    ("Переход круглого сечения", transition_round),
    ("Переход прямоугольного сечения", transition_rect),
    ("Переход с прямоугольного на круглое (≈)", transition_rect_to_round),
    ("Тройник круглого сечения (≈)", tee_round),
    ("Тройник круглого сечения с прямоугольной врезкой (≈)", tee_round_rect_branch),
    ("Тройник прямоугольного сечения (≈)", tee_rect),
    ("Тройник прямоугольного сечения с круглой врезкой (≈)", tee_rect_round_branch),
    ("Заглушка круглого сечения", cap_round),
    ("Заглушка прямоугольного сечения", cap_rect),
    ("Утка круглого сечения (≈)", duck_round),
    ("Утка прямоугольного сечения (≈)", duck_rect),
    ("Крестовина круглого сечения (≈)", cross_round),
    ("Крестовина прямоугольного сечения (≈)", cross_rect),
    ("Зонт островного типа", hood_island),
    ("Зонт пристенного типа (≈)", hood_wall),
    ("Зонт круглого сечения", hood_round),
    ("Дефлектор (≈)", deflector),
    ("Зонт прямоугольный с коньком", hood_rect_ridge),
    ("Зонт прямоугольный скошенный", hood_rect_beveled),
]


def main():
    print("=" * 60)
    print(" РАСЧЁТ ПЛОЩАДИ ВОЗДУХОВОДОВ И ФАСОННЫХ ИЗДЕЛИЙ (офлайн)")
    print(" Все размеры — в мм, углы — в градусах, площадь — в м²")
    print(" Пункты с (≈) считаются по инженерному приближению")
    print("=" * 60)
    while True:
        print("\nВыберите тип изделия:")
        for i, (name, _) in enumerate(MENU, start=1):
            print(f" {i:2d}. {name}")
        print("  0. Выход")
        choice = input("\nВаш выбор: ").strip()
        if choice == "0":
            print("До свидания!")
            sys.exit(0)
        try:
            idx = int(choice) - 1
            if idx < 0 or idx >= len(MENU):
                raise ValueError
        except ValueError:
            print("Некорректный выбор, попробуйте снова.")
            continue
        try:
            MENU[idx][1]()
        except KeyboardInterrupt:
            print("\nОтменено.")
        except Exception as e:
            print(f"Ошибка ввода/расчёта: {e}")
        pause()


if __name__ == "__main__":
    main()
