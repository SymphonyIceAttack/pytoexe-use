#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
РАСЧЁТ ПЛОЩАДИ ВОЗДУХОВОДОВ И ФАСОННЫХ ИЗДЕЛИЙ (офлайн-версия)
================================================================
Автономный (без интернета) калькулятор площади поверхности воздуховодов
и фасонных частей систем вентиляции — по мотивам онлайн-калькулятора
helpeng.ru/ov/ventilation/square-duct.

ВАЖНО ОБ ИСТОЧНИКЕ ФОРМУЛ
-------------------------
Сам сайт считает результат через скрытый JS-код (в статической странице
формулы не публикуются), поэтому здесь применены СТАНДАРТНЫЕ инженерные
формулы, используемые в практике раскроя листового металла для
воздуховодов и фасонных изделий (площадь чистой развёртки поверхности,
БЕЗ припусков на фальцы/замки и без учёта отходов — как и указано на
сайте). Для прямых участков, отводов и переходов формулы точные
(геометрия цилиндра/конуса/призмы). Для тройников, крестовин, "уток"
и зонтов сложной формы (где реальная развёртка требует построения
выкройки) применены общепринятые ИНЖЕНЕРНЫЕ ПРИБЛИЖЕНИЯ — они помечены
в выводе словом "≈ приближённо" и по возможности стоит сверять
критичные размеры с точной выкройкой или с сайтом.

Все линейные размеры вводятся в МИЛЛИМЕТРАХ, углы — в ГРАДУСАХ.
Результат площади выводится в м² (на 1 изделие и на заданное количество).

Запуск: python3 duct_calculator.py
"""

import math
import sys

MM2_TO_M2 = 1_000_000.0  # мм² -> м²


# ---------------------------------------------------------------------
# Вспомогательные функции ввода
# ---------------------------------------------------------------------

def read_float(prompt, default=None):
    while True:
        raw = input(f"{prompt}" + (f" [{default}]" if default is not None else "") + ": ").strip()
        if raw == "" and default is not None:
            return float(default)
        try:
            return float(raw.replace(",", "."))
        except ValueError:
            print("  Введите число (например 250 или 250.5).")


def read_int(prompt, default=1):
    while True:
        raw = input(f"{prompt} [{default}]: ").strip()
        if raw == "":
            return int(default)
        try:
            return int(raw)
        except ValueError:
            print("  Введите целое число.")


def show_result(area_mm2_per_unit, qty, label="Площадь одного изделия"):
    s1 = area_mm2_per_unit / MM2_TO_M2
    total = s1 * qty
    print("\n" + "-" * 50)
    print(f"{label}: {s1:.4f} м²")
    print(f"Количество: {qty} шт.")
    print(f"ИТОГО площадь: {total:.4f} м²")
    print("-" * 50 + "\n")


def pause():
    input("Нажмите Enter чтобы вернуться в меню...")


# ---------------------------------------------------------------------
# 1-2. ПРЯМОЙ УЧАСТОК
# ---------------------------------------------------------------------

def straight_round():
    print("\n[Прямой участок воздуховода круглого сечения]  S = π·D·L")
    D = read_float("Диаметр D, мм")
    L = read_float("Длина участка L, мм")
    n = read_int("Количество, шт")
    s = math.pi * D * L
    show_result(s, n)


def straight_rect():
    print("\n[Прямой участок воздуховода прямоугольного сечения]  S = 2·(a+b)·L")
    a = read_float("Сторона a, мм")
    b = read_float("Сторона b, мм")
    L = read_float("Длина участка L, мм")
    n = read_int("Количество, шт")
    s = 2 * (a + b) * L
    show_result(s, n)


# ---------------------------------------------------------------------
# 3-4. ОТВОДЫ (гнутый / секционный отвод, точная формула развёртки трубы)
# ---------------------------------------------------------------------

def elbow_round():
    print("\n[Отвод круглого сечения]  S = π·D·R·θ  (θ — угол поворота в радианах)")
    D = read_float("Диаметр D, мм")
    angle = read_float("Угол поворота отвода, град", default=90)
    R = read_float("Радиус закругления по оси отвода R, мм (обычно 1.5·D)", default=round(1.5 * D, 1))
    n = read_int("Количество, шт")
    theta = math.radians(angle)
    s = math.pi * D * R * theta
    show_result(s, n)


def elbow_rect():
    print("\n[Отвод прямоугольного сечения]  S = 2·(a+b)·R·θ")
    a = read_float("Сторона a (не меняется по ходу поворота), мм")
    b = read_float("Сторона b (в плоскости поворота), мм")
    angle = read_float("Угол поворота отвода, град", default=90)
    R = read_float("Радиус по оси отвода R, мм (обычно 1.5·b)", default=round(1.5 * b, 1))
    n = read_int("Количество, шт")
    theta = math.radians(angle)
    s = 2 * (a + b) * R * theta
    show_result(s, n)


# ---------------------------------------------------------------------
# 5-7. ПЕРЕХОДЫ (конус / усечённая пирамида)
# ---------------------------------------------------------------------

def transition_round():
    print("\n[Переход круглого сечения]  усечённый конус: S = π·(D1+D2)/2·l")
    D1 = read_float("Диаметр большего основания D1, мм")
    D2 = read_float("Диаметр меньшего основания D2, мм")
    L = read_float("Длина перехода (высота) L, мм")
    n = read_int("Количество, шт")
    l = math.hypot(L, (D1 - D2) / 2)
    s = math.pi * (D1 + D2) / 2 * l
    show_result(s, n)


def transition_rect():
    print("\n[Переход прямоугольного сечения]  усечённая пирамида (4 трапеции)")
    a1 = read_float("Сторона a1 (низ), мм")
    b1 = read_float("Сторона b1 (низ), мм")
    a2 = read_float("Сторона a2 (верх), мм")
    b2 = read_float("Сторона b2 (верх), мм")
    L = read_float("Длина перехода (высота) L, мм")
    n = read_int("Количество, шт")
    la = math.hypot(L, (a1 - a2) / 2)
    lb = math.hypot(L, (b1 - b2) / 2)
    s = (a1 + a2) * la + (b1 + b2) * lb
    show_result(s, n)


def transition_rect_to_round():
    print("\n[Переход с прямоугольного на круглое]  ≈ приближённо (по среднему периметру)")
    a = read_float("Сторона a прямоугольника, мм")
    b = read_float("Сторона b прямоугольника, мм")
    D = read_float("Диаметр круглого сечения D, мм")
    L = read_float("Длина перехода (высота) L, мм")
    n = read_int("Количество, шт")
    P_rect = 2 * (a + b)
    P_round = math.pi * D
    l = math.hypot(L, (max(a, b) - D) / 2)
    s = (P_rect + P_round) / 2 * l
    show_result(s, n)


# ---------------------------------------------------------------------
# 8-11. ТРОЙНИКИ (≈ приближённо: сумма поверхностей магистрали и врезки,
#         без вычета отверстия под врезку)
# ---------------------------------------------------------------------

def tee_round():
    print("\n[Тройник круглого сечения]  ≈ приближённо: S = π·D·Lm + π·d·Lb")
    D = read_float("Диаметр магистрали D, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    d = read_float("Диаметр врезки d, мм")
    Lb = read_float("Длина врезки Lb, мм")
    n = read_int("Количество, шт")
    s = math.pi * D * Lm + math.pi * d * Lb
    show_result(s, n)


def tee_round_rect_branch():
    print("\n[Тройник круглого сечения с прямоугольной врезкой]  ≈ приближённо")
    D = read_float("Диаметр магистрали D, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    a = read_float("Сторона a врезки, мм")
    b = read_float("Сторона b врезки, мм")
    Lb = read_float("Длина врезки Lb, мм")
    n = read_int("Количество, шт")
    s = math.pi * D * Lm + 2 * (a + b) * Lb
    show_result(s, n)


def tee_rect():
    print("\n[Тройник прямоугольного сечения]  ≈ приближённо")
    a = read_float("Сторона a магистрали, мм")
    b = read_float("Сторона b магистрали, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    a2 = read_float("Сторона a2 врезки, мм")
    b2 = read_float("Сторона b2 врезки, мм")
    Lb = read_float("Длина врезки Lb, мм")
    n = read_int("Количество, шт")
    s = 2 * (a + b) * Lm + 2 * (a2 + b2) * Lb
    show_result(s, n)


def tee_rect_round_branch():
    print("\n[Тройник прямоугольного сечения с круглой врезкой]  ≈ приближённо")
    a = read_float("Сторона a магистрали, мм")
    b = read_float("Сторона b магистрали, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    d = read_float("Диаметр врезки d, мм")
    Lb = read_float("Длина врезки Lb, мм")
    n = read_int("Количество, шт")
    s = 2 * (a + b) * Lm + math.pi * d * Lb
    show_result(s, n)


# ---------------------------------------------------------------------
# 12-13. ЗАГЛУШКИ (плоский диск / прямоугольник)
# ---------------------------------------------------------------------

def cap_round():
    print("\n[Заглушка круглого сечения]  S = π·D²/4")
    D = read_float("Диаметр D, мм")
    n = read_int("Количество, шт")
    s = math.pi * D ** 2 / 4
    show_result(s, n)


def cap_rect():
    print("\n[Заглушка прямоугольного сечения]  S = a·b")
    a = read_float("Сторона a, мм")
    b = read_float("Сторона b, мм")
    n = read_int("Количество, шт")
    s = a * b
    show_result(s, n)


# ---------------------------------------------------------------------
# 14-15. "УТКА" (S-образный обвод: два отвода + прямая вставка)
# ---------------------------------------------------------------------

def duck_round():
    print("\n[Утка круглого сечения]  ≈ 2 отвода + прямая вставка")
    D = read_float("Диаметр D, мм")
    angle = read_float("Угол одного колена утки, град", default=45)
    R = read_float("Радиус закругления колена R, мм (обычно 1.5·D)", default=round(1.5 * D, 1))
    Ls = read_float("Длина прямой вставки между коленами Ls, мм", default=0)
    n = read_int("Количество, шт")
    theta = math.radians(angle)
    s = 2 * (math.pi * D * R * theta) + math.pi * D * Ls
    show_result(s, n)


def duck_rect():
    print("\n[Утка прямоугольного сечения]  ≈ 2 отвода + прямая вставка")
    a = read_float("Сторона a, мм")
    b = read_float("Сторона b (в плоскости поворота), мм")
    angle = read_float("Угол одного колена утки, град", default=45)
    R = read_float("Радиус закругления колена R, мм (обычно 1.5·b)", default=round(1.5 * b, 1))
    Ls = read_float("Длина прямой вставки между коленами Ls, мм", default=0)
    n = read_int("Количество, шт")
    theta = math.radians(angle)
    s = 2 * (2 * (a + b) * R * theta) + 2 * (a + b) * Ls
    show_result(s, n)


# ---------------------------------------------------------------------
# 16-17. КРЕСТОВИНЫ (≈ магистраль + 2 симметричных врезки)
# ---------------------------------------------------------------------

def cross_round():
    print("\n[Крестовина круглого сечения]  ≈ приближённо: магистраль + 2 врезки")
    D = read_float("Диаметр магистрали D, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    d = read_float("Диаметр врезок d, мм")
    Lb = read_float("Длина одной врезки Lb, мм")
    n = read_int("Количество, шт")
    s = math.pi * D * Lm + 2 * (math.pi * d * Lb)
    show_result(s, n)


def cross_rect():
    print("\n[Крестовина прямоугольного сечения]  ≈ приближённо: магистраль + 2 врезки")
    a = read_float("Сторона a магистрали, мм")
    b = read_float("Сторона b магистрали, мм")
    Lm = read_float("Длина магистрального участка Lm, мм")
    a2 = read_float("Сторона a2 врезок, мм")
    b2 = read_float("Сторона b2 врезок, мм")
    Lb = read_float("Длина одной врезки Lb, мм")
    n = read_int("Количество, шт")
    s = 2 * (a + b) * Lm + 2 * (2 * (a2 + b2) * Lb)
    show_result(s, n)


# ---------------------------------------------------------------------
# 18-19. ЗОНТЫ ОСТРОВНОГО / ПРИСТЕННОГО ТИПА (усечённая пирамида, открытая снизу)
# ---------------------------------------------------------------------

def hood_island():
    print("\n[Зонт островного типа]  усечённая пирамида, 4 ската: S=(A+a)·la+(B+b)·lb")
    A = read_float("Больший размер по стороне A (низ), мм")
    a = read_float("Меньший размер по стороне A (верх/патрубок), мм")
    B = read_float("Больший размер по стороне B (низ), мм")
    b = read_float("Меньший размер по стороне B (верх/патрубок), мм")
    H = read_float("Высота зонта H, мм")
    n = read_int("Количество, шт")
    la = math.hypot(H, (A - a) / 2)
    lb = math.hypot(H, (B - b) / 2)
    s = (A + a) * la + (B + b) * lb
    show_result(s, n)


def hood_wall():
    print("\n[Зонт пристенного типа]  как островной, но без заднего ската (у стены)")
    A = read_float("Больший размер по стороне A (низ), мм")
    a = read_float("Меньший размер по стороне A (верх/патрубок), мм")
    B = read_float("Больший размер по стороне B (низ), мм")
    b = read_float("Меньший размер по стороне B (верх/патрубок), мм")
    H = read_float("Высота зонта H, мм")
    n = read_int("Количество, шт")
    la = math.hypot(H, (A - a) / 2)
    lb = math.hypot(H, (B - b) / 2)
    s_island = (A + a) * la + (B + b) * lb
    s = s_island - (A + a) / 2 * la  # минус задний скат у стены
    show_result(s, n)


# ---------------------------------------------------------------------
# 20-21. ЗОНТ КРУГЛОГО СЕЧЕНИЯ / ДЕФЛЕКТОР
# ---------------------------------------------------------------------

def hood_round():
    print("\n[Зонт круглого сечения]  усечённый конус: S = π·(D1+D2)/2·l")
    D1 = read_float("Диаметр низа D1, мм")
    D2 = read_float("Диаметр патрубка D2, мм")
    H = read_float("Высота зонта H, мм")
    n = read_int("Количество, шт")
    l = math.hypot(H, (D1 - D2) / 2)
    s = math.pi * (D1 + D2) / 2 * l
    show_result(s, n)


def deflector():
    print("\n[Дефлектор]  ≈ приближённо: колпак (конус) + патрубок (цилиндр)")
    D = read_float("Диаметр патрубка (воздуховода) D, мм")
    Dh = read_float("Диаметр колпака (зонта) Dh, мм", default=round(1.9 * D, 1))
    H_cone = read_float("Высота конуса колпака H, мм", default=round(0.5 * D, 1))
    H_pipe = read_float("Высота цилиндрической части патрубка Hp, мм", default=round(1.0 * D, 1))
    n = read_int("Количество, шт")
    l = math.hypot(H_cone, (Dh - D) / 2)
    s_cone = math.pi * (Dh + D) / 2 * l
    s_pipe = math.pi * D * H_pipe
    s = s_cone + s_pipe
    show_result(s, n)


# ---------------------------------------------------------------------
# 22-23. ЗОНТ ПРЯМОУГОЛЬНЫЙ С КОНЬКОМ / СКОШЕННЫЙ
# ---------------------------------------------------------------------

def hood_rect_ridge():
    print("\n[Зонт прямоугольный с коньком]  2 ската вдоль конька: S = 2·A·ls")
    A = read_float("Длина зонта вдоль конька A, мм")
    B = read_float("Ширина зонта (в поперечном направлении) B, мм")
    H = read_float("Высота конька над основанием H, мм")
    n = read_int("Количество, шт")
    ls = math.hypot(H, B / 2)
    s = 2 * A * ls
    show_result(s, n)


def hood_rect_beveled():
    print("\n[Зонт прямоугольный скошенный]  1 скат + 2 боковые трапеции")
    A = read_float("Длина зонта A, мм")
    B = read_float("Ширина (глубина ската) B, мм")
    H1 = read_float("Высота переднего края H1, мм")
    H2 = read_float("Высота заднего края H2, мм")
    n = read_int("Количество, шт")
    slant = math.hypot(H1 - H2, B)
    s_top = A * slant
    s_sides = 2 * ((H1 + H2) / 2 * B)
    s = s_top + s_sides
    show_result(s, n)


